CREATE TABLE TB_RS_USER (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name NVARCHAR2(255) NOT NULL,
    email NVARCHAR2(255) NOT NULL UNIQUE,
    password NVARCHAR2(255) NOT NULL,
    createdAt TIMESTAMP NOT NULL DEFAULT SYSTIMESTAMP
);

CREATE TABLE TB_RS_SKILL (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name NVARCHAR2(255) NOT NULL,
    USER_ID NUMBER NOT NULL,
    CONSTRAINT fk_skill_user FOREIGN KEY (USER_ID) REFERENCES TB_RS_USER(id)
);

CREATE TABLE TB_RS_PLANNING (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    goal NVARCHAR2(255) NOT NULL,
    recommendation CLOB NOT NULL,
    createdAt TIMESTAMP NOT NULL DEFAULT SYSTIMESTAMP,
    USER_ID NUMBER NOT NULL,
    CONSTRAINT fk_planning_user FOREIGN KEY (USER_ID) REFERENCES TB_RS_USER(id)
);

CREATE TABLE TB_RS_PLANNING_ITEM (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DESCRIPTION NVARCHAR2(255) NOT NULL,
    COMPLETED NUMBER(1) NOT NULL DEFAULT 0,
    PLANNING_ID NUMBER NOT NULL,
    CONSTRAINT fk_planning_item_planning FOREIGN KEY (PLANNING_ID) REFERENCES TB_RS_PLANNING(id)
);